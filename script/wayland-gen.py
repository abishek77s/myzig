#!/usr/bin/env python3
"""Generates src/wayland/protocol.zig from the protocol XML in
vendor/wayland: each interface as a Zig type with its requests as methods,
its events as a tagged union taken by setListener, and its enums as
constants. Run it after changing what is vendored:

    script/wayland-gen.py
"""
import os
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [
    "wayland.xml",
    "xdg-shell.xml",
    "xdg-decoration-unstable-v1.xml",
    "text-input-unstable-v3.xml",
    "cursor-shape-v1.xml",
    "fractional-scale-v1.xml",
    "viewporter.xml",
]

KEYWORDS = set(
    "addrspace align allowzero and anyframe anytype asm break callconv catch comptime const continue "
    "defer else enum errdefer error export extern fn for if inline noalias nosuspend noinline opaque or "
    "orelse packed pub resume return linksection struct suspend switch test threadlocal try union "
    "unreachable usingnamespace var volatile while".split()
)


def ident(name):
    if name in KEYWORDS or name[0].isdigit():
        return '@"%s"' % name
    return name


def camel(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def summary(el):
    d = el.find("description")
    if d is not None and d.get("summary"):
        return " ".join(d.get("summary").split())
    return None


ifaces = []
for f in FILES:
    tree = ET.parse(os.path.join(ROOT, "vendor", "wayland", f))
    for it in tree.getroot().findall("interface"):
        ifaces.append(it)
known = {it.get("name") for it in ifaces}


def wire(msg):
    """The message's signature and the interfaces of its wire arguments."""
    sig = ""
    types = []
    if msg.get("since") and msg.get("since") != "1":
        sig += msg.get("since")
    for a in msg.findall("arg"):
        t = a.get("type")
        nullable = a.get("allow-null") == "true"
        if t == "new_id" and not a.get("interface"):
            sig += "sun"
            types += [None, None, None]
            continue
        code = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o", "new_id": "n", "array": "a", "fd": "h"}[t]
        sig += ("?" if nullable else "") + code
        iface = a.get("interface") if t in ("object", "new_id") else None
        types.append(iface if iface in known else None)
    return sig, types


def ptr_type(iface, nullable=True):
    if iface in known:
        return ("?*" if nullable else "*") + iface
    return "?*anyopaque" if nullable else "*anyopaque"


out = []
w = out.append
w("// Generated by script/wayland-gen.py from vendor/wayland; do not edit.")
w("")
w('const client = @import("client.zig");')
w("const Argument = client.Argument;")
w("")

for it in ifaces:
    name = it.get("name")
    reqs = it.findall("request")
    evs = it.findall("event")
    s = summary(it)
    if s:
        w("/// " + s)
    w("pub const %s = opaque {" % name)
    w("    pub const interface: *const client.Interface = &%s_interface;" % name)
    w("")
    # Enums, as constants.
    for en in it.findall("enum"):
        w("    pub const %s = struct {" % camel(en.get("name")))
        for e in en.findall("entry"):
            w("        pub const %s: u32 = %s;" % (ident(e.get("name")), e.get("value")))
        w("    };")
        w("")
    # Requests.
    has_destroy = False
    for op, r in enumerate(reqs):
        rname = r.get("name")
        if rname == "destroy":
            has_destroy = True
        params = ["self: *%s" % name]
        args = []
        ret = "void"
        new_iface = None
        generic = False
        for a in r.findall("arg"):
            an = ident(a.get("name"))
            t = a.get("type")
            nullable = a.get("allow-null") == "true"
            if t == "new_id":
                if a.get("interface"):
                    new_iface = a.get("interface")
                    ret = "?*" + new_iface
                    args.append(".{ .n = 0 }")
                else:
                    generic = True
                    params.append("comptime T: type")
                    params.append("ver: u32")
                    ret = "?*T"
                    args += [".{ .s = T.interface.name }", ".{ .u = ver }", ".{ .n = 0 }"]
                continue
            if t == "int":
                params.append("%s: i32" % an)
                args.append(".{ .i = %s }" % an)
            elif t == "uint":
                params.append("%s: u32" % an)
                args.append(".{ .u = %s }" % an)
            elif t == "fixed":
                params.append("%s: f64" % an)
                args.append(".{ .f = client.floatToFixed(%s) }" % an)
            elif t == "string":
                params.append("%s: %s[*:0]const u8" % (an, "?" if nullable else ""))
                args.append(".{ .s = %s }" % an)
            elif t == "object":
                params.append("%s: %s" % (an, ptr_type(a.get("interface"), nullable)))
                args.append(".{ .o = @ptrCast(%s) }" % an)
            elif t == "array":
                params.append("%s: *client.Array" % an)
                args.append(".{ .a = %s }" % an)
            elif t == "fd":
                params.append("%s: i32" % an)
                args.append(".{ .h = %s }" % an)
        flags = "client.marshal_destroy" if r.get("type") == "destructor" else "0"
        s = summary(r)
        if s:
            w("    /// " + s)
        w("    pub fn %s(%s) %s {" % (ident(rname), ", ".join(params), ret))
        w("        var a_ = [_]Argument{%s};" % (" " + ", ".join(args) + " " if args else ""))
        if generic:
            # The registry's bind: the name comes first.
            w("        return @ptrCast(client.marshal(self, %d, T.interface, ver, %s, &a_));" % (op, flags))
        elif new_iface:
            iface_ref = "&%s_interface" % new_iface
            w("        return @ptrCast(client.marshal(self, %d, %s, client.version(self), %s, &a_));" % (op, iface_ref, flags))
        else:
            w("        _ = client.marshal(self, %d, null, client.version(self), %s, &a_);" % (op, flags))
        w("    }")
        w("")
    if not has_destroy:
        w("    pub fn destroy(self: *%s) void {" % name)
        w("        client.lib.proxy_destroy(@ptrCast(self));")
        w("    }")
        w("")
    # Events.
    if evs:
        w("    pub const Event = union(enum) {")
        for e in evs:
            fields = []
            for a in e.findall("arg"):
                an = ident(a.get("name"))
                t = a.get("type")
                ft = {
                    "int": "i32",
                    "uint": "u32",
                    "fixed": "f64",
                    "string": "?[*:0]const u8",
                    "array": "*client.Array",
                    "fd": "i32",
                }.get(t)
                if t == "object":
                    ft = ptr_type(a.get("interface"))
                elif t == "new_id":
                    ft = ptr_type(a.get("interface"), nullable=False)
                fields.append("%s: %s" % (an, ft))
            s = summary(e)
            if s:
                w("        /// " + s)
            w("        %s: struct {%s}," % (ident(e.get("name")), (" " + ", ".join(fields) + " ") if fields else ""))
        w("    };")
        w("")
        w("    /// setListener has handler take this object's events, with data.")
        w("    pub fn setListener(self: *%s, comptime T: type, comptime handler: fn (*%s, Event, T) void, data: T) void {" % (name, name))
        w("        const D = struct {")
        w("            fn dispatch(_: ?*const anyopaque, proxy: ?*anyopaque, opcode: u32, _: ?*const client.Message, args: [*]Argument) callconv(.c) c_int {")
        w("                const p = proxy.?;")
        if not any(e.findall("arg") for e in evs):
            w("                _ = args;")
        w("                const ev: Event = switch (opcode) {")
        for op, e in enumerate(evs):
            inits = []
            for k, a in enumerate(e.findall("arg")):
                an = ident(a.get("name"))
                t = a.get("type")
                v = {
                    "int": "args[%d].i",
                    "uint": "args[%d].u",
                    "fixed": "client.fixedToFloat(args[%d].f)",
                    "string": "args[%d].s",
                    "array": "args[%d].a.?",
                    "fd": "args[%d].h",
                }.get(t)
                if t == "object":
                    v = "@ptrCast(args[%d].o)"
                elif t == "new_id":
                    v = "@ptrCast(args[%d].o.?)"
                inits.append(".%s = %s" % (an, v % k))
            w("                    %d => .{ .%s = .{%s} }," % (op, ident(e.get("name")), (" " + ", ".join(inits) + " ") if inits else ""))
        w("                    else => return 0,")
        w("                };")
        w("                const ud = client.lib.proxy_get_user_data(p);")
        w("                handler(@ptrCast(p), ev, if (@typeInfo(T) == .optional) @ptrCast(@alignCast(ud)) else @ptrCast(@alignCast(ud.?)));")
        w("                return 0;")
        w("            }")
        w("        };")
        w("        _ = client.lib.proxy_add_dispatcher(@ptrCast(self), D.dispatch, null, @ptrCast(@constCast(data)));")
        w("    }")
    w("};")
    w("")


def messages(msgs):
    rows = []
    for m in msgs:
        sig, types = wire(m)
        if types:
            ts = ", ".join("&%s_interface" % t if t else "null" for t in types)
            rows.append('    .{ .name = "%s", .signature = "%s", .types = &[_]?*const client.Interface{ %s } },' % (m.get("name"), sig, ts))
        else:
            rows.append('    .{ .name = "%s", .signature = "%s", .types = null },' % (m.get("name"), sig))
    return rows


for it in ifaces:
    name = it.get("name")
    reqs = it.findall("request")
    evs = it.findall("event")
    if reqs:
        w("const %s_requests = [_]client.Message{" % name)
        out.extend(messages(reqs))
        w("};")
    if evs:
        w("const %s_events = [_]client.Message{" % name)
        out.extend(messages(evs))
        w("};")
    w("pub var %s_interface: client.Interface = .{" % name)
    w('    .name = "%s",' % name)
    w("    .version = %s," % it.get("version"))
    w("    .method_count = %d," % len(reqs))
    w("    .methods = %s," % ("&%s_requests" % name if reqs else "null"))
    w("    .event_count = %d," % len(evs))
    w("    .events = %s," % ("&%s_events" % name if evs else "null"))
    w("};")
    w("")

path = os.path.join(ROOT, "src", "wayland", "protocol.zig")
with open(path, "w") as fh:
    fh.write("\n".join(out))
# zig fmt's layout, as the style check wants it.
subprocess.run(["zig", "fmt", path], check=False, stdout=subprocess.DEVNULL)
print("wrote", path, "(%d interfaces)" % len(ifaces), file=sys.stderr)
